"""Pixel support is per measurement; no SAM, robot or simulator is started."""

from types import SimpleNamespace

import numpy as np
import pytest

from pyrualean.hosts import robodojo_kinematics as kin
from pyrualean.hosts import robodojo_sight as sight
from pyrualean.hosts import robodojo_tools as tools


@pytest.fixture
def pixel_world():
    image = np.zeros((480, 640, 3), dtype=np.uint8)
    mask = np.zeros(image.shape[:2], dtype=bool)
    mask[298:303, 318:323] = True
    obs = {"vision": {"cam_head": {"color": image}}, "state": {}}
    segmenter = SimpleNamespace(segment=lambda *a, **k: SimpleNamespace(found=True, mask=mask))
    prim = SimpleNamespace(env=SimpleNamespace(get_obs=lambda: obs), sam3_client=segmenter)
    return prim, obs, mask


@pytest.mark.parametrize("existing", [False, True])
def test_geometry_without_new_pixel_support_does_not_read_old_region(
    pixel_world, monkeypatch, existing,
):
    prim, obs, _ = pixel_world
    scene = tools._scene(prim, obs)
    reads = []

    class EarlierRegion(dict):
        def __getitem__(self, key):
            if key == "rows":
                reads.append(key)
            return super().__getitem__(key)

    if existing:
        scene["regions"].append(EarlierRegion(
            camera="cam_head", rows=np.array([100]), cols=np.array([100]),
            points=np.array([[.2, .1, .9]]),
        ))
    monkeypatch.setattr(tools, "_measure_in_colour", lambda *a: ({"top_z": .9}, {}))
    result = tools.probe(prim, 300, 320)
    assert result["surface"] == "table"
    assert result["world_xyz"][2] == kin.TABLE_Z
    # The initial same-image cache lookup is allowed, but is never reread as
    # if it had been generated by the new measurement.
    assert len(reads) == (2 if existing else 0)
    assert not scene.get("flat")  # Missing pixel support is not evidence of a flat object.


def test_probe_uses_the_new_region_for_its_pixel(pixel_world, monkeypatch):
    prim, obs, _ = pixel_world
    scene = tools._scene(prim, obs)
    xyz = [.01, -.02, .82]

    def measure(*args):
        scene["regions"].append({"camera": "cam_head", "rows": np.array([300]),
                                 "cols": np.array([320]), "points": np.array([xyz])})
        scene["regions"].append({"camera": "cam_head", "rows": np.array([100]),
                                 "cols": np.array([100]), "points": np.array([[.2, .1, .9]])})
        return {"top_z": .9}, {}

    monkeypatch.setattr(tools, "_measure_in_colour", measure)
    result = tools.probe(prim, 300, 320)
    assert result["surface"] == "object"
    assert result["world_xyz"] == xyz


def test_occluded_single_view_geometry_registers_its_pixel_support(pixel_world, monkeypatch):
    prim, obs, mask = pixel_world
    rows, cols = np.nonzero(mask)
    xy, valid = sight.head_view().on_plane(rows, cols, .81)
    assert valid.all()
    points = np.column_stack([xy, np.full(len(rows), .81)])
    monkeypatch.setattr(sight, "measure", lambda *a, **k: {
        "views": 1, "rows": rows, "cols": cols, "points": points,
    })
    monkeypatch.setattr(sight, "robot_pixels", lambda *a, **k: np.zeros_like(mask))
    monkeypatch.setattr(tools, "_behind_robot", lambda *a: True)
    geometry, seen = tools._measure_in_colour(prim, obs, "cam_head", mask, None, 0.)
    assert geometry is not None
    assert "robot's arm is in front" in seen["guess"]
    assert len(tools._scene(prim, obs)["regions"]) == 1
    result = tools.probe(prim, 300, 320)
    assert result["surface"] == "object"
    assert result["world_xyz"][2] == .81
